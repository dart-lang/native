FfiGenerator getConfig({Uri? outputDir, Uri? packageRoot}) {
  packageRoot ??= Platform.script.resolve('../../../../jni/');
  final dartPath = outputDir != null
      ? outputDir.resolve('jni_bindings_generated.dart')
      : packageRoot.resolve('lib/src/third_party/jni_bindings_generated.dart');
  return FfiGenerator(
    output: Output(
      dart: DartOutput(path: dartPath),
      style: const DynamicLibraryBindings(
        wrapperName: 'JniBindings',
        wrapperDocComment: '''
Bindings for libdartjni.so which is part of jni plugin.

It also transitively includes type definitions such as JNIEnv from third_party/jni.h;

However, functions prefixed JNI_ are not usable because they are in a different shared library.

Regenerate bindings with `dart run ffigen --config ffigen.yaml`.
''',
      ),
      commentType: const CommentType(CommentStyle.any, CommentLength.full),
      preamble: '''
