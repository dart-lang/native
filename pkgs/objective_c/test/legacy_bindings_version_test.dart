import 'dart:io';

import 'package:native_test_helpers/native_test_helpers.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

void main() {
  final pkgDir = findPackageRoot('objective_c').toFilePath();

  group('legacy_test_runner ffigen 20.0.0 version guard', () {
    test('pubspec.yaml pins exact ffigen: 20.0.0', () {
      final pubspec = File(
        p.join(pkgDir, 'legacy_test_runner', 'pubspec.yaml'),
      ).readAsStringSync();
      expect(
        RegExp(
          r'^\s*ffigen:\s*20\.0\.0\s*$',
          multiLine: true,
        ).hasMatch(pubspec),
        isTrue,
        reason:
            'legacy_test_runner/pubspec.yaml must pin exact ffigen: 20.0.0 '
            '(without a caret) to test backwards compatibility.',
      );
    });

    test('legacy_bindings.g.dart was generated by ffigen 20.0.0', () {
      final bindings = File(
        p.join(pkgDir, 'legacy_test_runner', 'lib', 'legacy_bindings.g.dart'),
      ).readAsStringSync();
      expect(
        bindings.contains('ObjCVersionCheck'),
        isFalse,
        reason:
            'legacy_bindings.g.dart must stay generated by ffigen 20.0.0 '
            '(which pre-dates ObjCVersionCheck).',
      );
    });
  });
}
