// Generates bindings frozen at ffigen 20.0.0 to test backwards compatibility
// with current package:objective_c.
//
// Regenerate via: dart run tool/ffigen.dart

import 'dart:io';

import 'package:ffigen/ffigen.dart';
import 'package:logging/logging.dart';

void main() {
  final packageRoot = Platform.script.resolve('../');
  final generator = FfiGenerator(
    headers: Headers(
      entryPoints: [packageRoot.resolve('src/legacy_fixture.h')],
    ),
    functions: Functions.includeSet({'legacyAddInts'}),
    globals: Globals.includeSet({'kLegacyMagicNumber'}),
    structs: Structs.includeSet({'LegacyPoint'}),
    enums: Enums.includeSet({'LegacyColor', 'LegacyFlags'}),
    objectiveC: ObjectiveC(
      interfaces: Interfaces.includeSet({
        'LegacyBase',
        'LegacyChild',
        'LegacyObjCDelegate',
      }),
      protocols: Protocols.includeSet({'LegacyDelegate'}),
      categories: Categories.includeSet({'LegacyExtra', 'LegacyStringExtra'}),
    ),
    output: Output(
      dartFile: packageRoot.resolve('lib/legacy_bindings.g.dart'),
      objectiveCFile: packageRoot.resolve('src/legacy_bindings.m'),
      style: const NativeExternalBindings(
        assetId: 'package:legacy_test_runner/legacy_bindings.g.dart',
      ),
      preamble: '''
// Copyright (c) 2026, the Dart project authors.  Please see the AUTHORS file
// for details. All rights reserved. Use of this source code is governed by a
// BSD-style license that can be found in the LICENSE file.
//
// Generated by ffigen 20.0.0. Do not regenerate with a newer version of ffigen.
// ignore_for_file: unused_element
''',
    ),
  );

  Logger.root.level = Level.WARNING;
  Logger.root.onRecord.listen((record) {
    stderr.writeln('${record.level.name}: ${record.message}');
  });
  generator.generate(logger: Logger.root);
}
