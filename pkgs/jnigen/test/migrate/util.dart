import '../test_util/test_util.dart';

final updateExpectations = Platform.environment['UPDATE'] == 'true';

String findOriginalPath(String fileName, String jnigenRoot) {
  final baseName = fileName.replaceAll('.yaml', '');
  if (baseName.startsWith('example_')) {
    final sub = baseName.replaceFirst('example_', '');
    return path.join(jnigenRoot, 'example', sub, 'jnigen.yaml');
  }
  if (baseName == 'test_jackson_core') {
    return path.join(jnigenRoot, 'test', 'jackson_core_test', 'jnigen.yaml');
  }
  if (baseName == 'test_dartify_simple_cases') {
    return path.join(jnigenRoot, 'test', 'simple_package_test', 'jnigen.yaml');
  }
  if (baseName == 'comprehensive') {
    return path.join(
      jnigenRoot,
      'test',
      'simple_package_test',
      'comprehensive.yaml',
    );
  }
  return path.join(jnigenRoot, 'test', 'migrate', 'yaml', fileName);
}

void _copyDirectory(Directory source, Directory destination) {
  for (final entity in source.listSync(recursive: false)) {
    final name = path.basename(entity.path);
    final newPath = path.join(destination.path, name);
    if (entity is Directory) {
      Directory(newPath).createSync(recursive: true);
      _copyDirectory(entity, Directory(newPath));
    } else if (entity is File) {
      entity.copySync(newPath);
    }
  }
}

Future<void> matchPathWithExpected({
  required String actualPath,
  required String expectedPath,
}) async {
  final expectedType = FileSystemEntity.typeSync(expectedPath);
  final actualType = FileSystemEntity.typeSync(actualPath);

  if (updateExpectations) {
    print(
      'Updating expectations: ${path.relative(expectedPath, from: pkgDir)}',
    );
    if (actualType == FileSystemEntityType.file) {
      File(expectedPath).parent.createSync(recursive: true);
      File(actualPath).copySync(expectedPath);
    } else if (actualType == FileSystemEntityType.directory) {
      final destDir = Directory(expectedPath);
      if (destDir.existsSync()) {
        destDir.deleteSync(recursive: true);
      }
      destDir.createSync(recursive: true);
      _copyDirectory(Directory(actualPath), destDir);
    } else if (expectedType != FileSystemEntityType.notFound) {
      if (expectedType == FileSystemEntityType.directory) {
        Directory(expectedPath).deleteSync(recursive: true);
      } else {
        File(expectedPath).deleteSync();
      }
    }
  }

  final actualExists = actualType != FileSystemEntityType.notFound;
  final expectedExists =
      FileSystemEntity.typeSync(expectedPath) != FileSystemEntityType.notFound;

  if (!actualExists || !expectedExists) {
    final diff = expectedExists
        ? "Expected file/dir exists, but actual doesn't"
        : "Expected file/dir doesn't exist, but actual does";
    fail('''
$diff

Expected output does not match actual output:
  ${path.relative(expectedPath, from: pkgDir)}
      vs
  ${path.relative(actualPath, from: pkgDir)}

If the diffs are expected, rerun with UPDATE=true
''');
  }

  final diffProc = Process.runSync('git', [
    'diff',
    '--no-index',
    if (stderr.supportsAnsiEscapes) '--color=always',
    expectedPath,
    actualPath,
  ]);
  if (diffProc.exitCode != 0) {
    fail('''
${diffProc.stdout}

Expected output does not match actual output:
  ${path.relative(expectedPath, from: pkgDir)}
      vs
  ${path.relative(actualPath, from: pkgDir)}

If the diffs are expected, rerun with UPDATE=true
''');
  }
}

void compareBindingDirectories(String expectedPath, String actualPath) {
  final expectedExists =
      FileSystemEntity.typeSync(expectedPath) != FileSystemEntityType.notFound;
  if (!expectedExists) {
    fail("Expected bindings don't exist at $expectedPath");
  }

  final actualType = FileSystemEntity.typeSync(actualPath);
  if (actualType == FileSystemEntityType.notFound) {
    fail("Actual bindings don't exist at $actualPath");
  }

  if (actualType == FileSystemEntityType.directory) {
    final files = Directory(actualPath)
        .listSync(recursive: true)
        .whereType<File>()
        .toList();
    if (files.isEmpty) {
      fail('No bindings generated by Dart script into $actualPath');
    }
  }

  final diffProc = Process.runSync('git', [
    'diff',
    '--no-index',
    if (stderr.supportsAnsiEscapes) '--color=always',
    expectedPath,
    actualPath,
  ]);
  if (diffProc.exitCode != 0) {
    fail(
      'Bindings generated from YAML and Dart script do not match:\n'
      '${diffProc.stdout}\n'
      '  $expectedPath\n'
      '      vs\n'
      '  $actualPath',
    );
  }
}

Future<void> verifyMigration(File yamlFile) async {
  final testName = path.basenameWithoutExtension(yamlFile.path);
  final origConfigPath = findOriginalPath(
    path.basename(yamlFile.path),
    pkgDir,
  );

  final tempDir = Directory.systemTemp.createTempSync('jnigen_migrate_test_');
  try {
    // 1. Generate YAML bindings and verify against checked-in copy.
    final origConfigFile = File(origConfigPath);
    final origExisted = origConfigFile.existsSync();
    if (!origExisted) {
      origConfigFile.parent.createSync(recursive: true);
      origConfigFile.writeAsStringSync(yamlFile.readAsStringSync());
    }

    final JniGenerator config;
    try {
      config = JniGenerator.parseArgs(['--config', origConfigPath]);
    } finally {
      if (!origExisted && origConfigFile.existsSync()) {
        origConfigFile.deleteSync();
      }
    }

    final actualYamlBindingsDir = Directory(
      path.join(tempDir.path, 'yaml_bindings', testName),
    )..createSync(recursive: true);

    final singleFile =
        config.output.dart.structure == OutputStructure.singleFile;
    final tempLibUri = singleFile
        ? actualYamlBindingsDir.uri.resolve('generated.dart')
        : actualYamlBindingsDir.uri.resolve('lib/');
    config.output.dart.path = tempLibUri;

    await config.generate();

    final checkedInBindingsPath = path.join(
      pkgDir,
      'test',
      'migrate',
      'bindings',
      testName,
    );

    await matchPathWithExpected(
      actualPath: actualYamlBindingsDir.path,
      expectedPath: checkedInBindingsPath,
    );

    // 2. Run YAML config through migrator and verify Dart script against
    // checked-in.
    final checkedInDartScriptPath = path.join(
      pkgDir,
      'test',
      'migrate',
      'dart',
      '$testName.dart',
    );
    final actualDartScriptFile = File(
      path.join(tempDir.path, 'dart', '$testName.dart'),
    )..parent.createSync(recursive: true);

    migrate(yamlConfig: yamlFile, outputDart: actualDartScriptFile);

    await matchPathWithExpected(
      actualPath: actualDartScriptFile.path,
      expectedPath: checkedInDartScriptPath,
    );

    // 3. Run the generated Dart script to generate bindings into temp location.
    final scriptToRun = File(checkedInDartScriptPath).existsSync()
        ? File(checkedInDartScriptPath)
        : actualDartScriptFile;

    final tempDartGenDir = Directory(
      path.join(tempDir.path, 'dart_gen', testName),
    )..createSync(recursive: true);

    final runResult = await Process.run(
      Platform.resolvedExecutable,
      ['run', scriptToRun.path, tempDartGenDir.path],
      workingDirectory: pkgDir,
      environment: {'OUTPUT_DIR': tempDartGenDir.path},
    );
    if (runResult.exitCode != 0) {
      fail(
        'Running Dart script ${scriptToRun.path} failed with exit code '
        '${runResult.exitCode}:\n'
        '${runResult.stderr}\n${runResult.stdout}',
      );
    }

    // 4. Verify that the two sets of generated bindings are the same.
    compareBindingDirectories(checkedInBindingsPath, tempDartGenDir.path);
  } finally {
    if (tempDir.existsSync()) {
      tempDir.deleteSync(recursive: true);
    }
  }
}
