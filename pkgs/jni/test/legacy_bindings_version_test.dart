import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:test/test.dart';

String _resolveRunnerFile(String relativePath) {
  final direct = p.join('legacy_android_test_runner', relativePath);
  if (File(direct).existsSync()) {
    return direct;
  }
  final fromRepoRoot = p.join(
    'pkgs',
    'jni',
    'legacy_android_test_runner',
    relativePath,
  );
  if (File(fromRepoRoot).existsSync()) {
    return fromRepoRoot;
  }
  throw StateError('Could not locate $relativePath from ${Directory.current}');
}

void main() {
  test('legacy bindings are generated by jnigen 0.16.0 (JniVersionCheck 1.0)',
      () {
    final bindings = File(
      _resolveRunnerFile(p.join('lib', 'legacy_bindings.g.dart')),
    ).readAsStringSync();

    expect(
        bindings, contains('// AUTO GENERATED BY JNIGEN 0.16.0. DO NOT EDIT!'));
    expect(bindings, contains('JniVersionCheck(1, 0)'));

    final versionChecks = RegExp(
      r'JniVersionCheck\(\d+,\s*\d+\)',
    ).allMatches(bindings).map((m) => m.group(0)).toSet();
    expect(versionChecks, equals({'JniVersionCheck(1, 0)'}));
  });

  test('legacy_android_test_runner pins jnigen to exact 0.16.0', () {
    final pubspec = File(_resolveRunnerFile('pubspec.yaml')).readAsStringSync();
    expect(
      pubspec,
      matches(RegExp(r'^\s*jnigen:\s*0\.16\.0\s*$', multiLine: true)),
    );
  });
}
